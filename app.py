import streamlit as st

from agent import run_agent
from observability.trace_store import init_db, save_run, list_runs, get_run

init_db()

st.set_page_config(
    page_title="Multi-Agent Freshness Research",
    page_icon="🤖",
    layout="wide",
)
st.title("🤖 Multi-Agent Research Agent")
st.caption(
    "Parallel LLM baseline | Tavily retrieval | Evidence-grounded refresh | "
    "Independent verification"
)

query = st.text_area(
    "Ask the agent",
    placeholder="What is the latest version of Go (Golang)?",
    height=100,
)

if st.button("Run Agent", type="primary"):
    if not query.strip():
        st.warning("Enter a query first.")
    else:
        # Avoid accidentally showing the previous run if this run fails.
        st.session_state.pop("result", None)
        with st.spinner("Generating baseline and retrieving Tavily evidence in parallel..."):
            try:
                result = run_agent(query.strip())
                st.session_state["result"] = result
                save_run(result, query.strip())
            except Exception as exc:
                st.error(f"Agent execution failed: {exc}")

if "result" in st.session_state:
    result = st.session_state["result"]
    freshness = result.get("freshness") or {}

    st.divider()
    st.subheader("Answer comparison")
    st.caption(
        "Original = LLM knowledge without Tavily. Refreshed = LLM answer "
        "generated using Tavily evidence."
    )

    col1, col2 = st.columns(2)

    with col1:
        st.markdown("### Original LLM answer")
        st.caption("Generated without web retrieval")
        original = result.get("original_answer")
        if original:
            st.markdown(original)
        else:
            st.warning("The original LLM answer could not be generated.")

        with st.expander("Original answer verification"):
            st.json(result.get("original_verification") or {})

    with col2:
        st.markdown("### Refreshed answer")
        st.caption("Generated by the LLM using Tavily search evidence")
        refreshed = result.get("refreshed_answer")
        if refreshed:
            st.markdown(refreshed)
        else:
            st.warning("The refresh agent did not generate an answer.")

        with st.expander("Refreshed answer verification"):
            st.json(result.get("refreshed_verification") or {})

    st.divider()
    st.subheader("Final answer")
    source = result.get("final_answer_source")
    if source == "refreshed":
        st.success("Accepted: refreshed answer (fresh evidence + supported claims)")
    elif source == "original_fallback":
        st.info("Accepted: original answer (refreshed candidate did not pass, but original claims did)")
    elif source == "original":
        st.info("Accepted: original answer (static/general query; no refresh required)")
    else:
        st.warning("No candidate passed the freshness and verification gates")

    st.markdown(result.get("answer") or "No final answer returned.")
    st.caption(
        f"Trace ID: {result.get('trace_id')} | "
        f"Time-sensitive: {freshness.get('time_sensitive')} | "
        f"Evidence status: {(freshness.get('evidence_freshness') or {}).get('status', 'not applicable')} | "
        f"Final verification: {freshness.get('verification_status')}"
    )

    with st.expander("Freshness classification"):
        st.json(result.get("original_freshness") or {})

    with st.expander("Tavily evidence sources"):
        st.json(result.get("evidence", {}))

    with st.expander("Agent execution trace"):
        for item in (result.get("trace") or {}).get("spans", []):
            label = (
                f"{item.get('agent_name')} 路 {item.get('status')} 路 "
                f"{item.get('duration_ms')} ms"
            )
            with st.expander(label):
                st.write("Span ID:", item.get("span_id"))
                st.write("Parent ID:", item.get("parent_id"))
                st.write("Started:", item.get("started_at"))
                st.write("Input:")
                st.json(item.get("input"))
                st.write("Output:")
                st.json(item.get("output"))
                if item.get("error"):
                    st.error(item["error"])

st.divider()
st.subheader("Saved run history")
try:
    history = list_runs(limit=30)
    if history:
        labels = [f"{row['created_at']} 路 {row['query'][:100]}" for row in history]
        selected = st.selectbox("Previous runs", labels)
        chosen = history[labels.index(selected)]
        if st.button("Load selected run"):
            st.session_state["history_run"] = get_run(chosen["trace_id"])
        if st.session_state.get("history_run"):
            st.json(st.session_state["history_run"])
    else:
        st.caption("No saved runs yet.")
except Exception as exc:
    st.warning(f"Could not load saved history: {exc}")
